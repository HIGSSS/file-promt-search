    print("\n=== XLSX ===")
    queries = []
    for i, (filename, query, sheet_name, rows) in enumerate(_XLSX_TOPICS, start=id_offset):
        path = out_dir / filename
        wb = openpyxl.Workbook()
        ws = wb.active
        ws.title = sheet_name
        for row in rows:
            ws.append(row)
        wb.save(str(path))
        queries.append({
            "id": i,
            "file_type": "xlsx",
            "query": query,
            "kind": "semantic",
            "relevant": [filename],
        })
        print(f"  {filename}  <- \"{query}\"")
    return queries


