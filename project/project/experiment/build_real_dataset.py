def _build_pdfs(out_dir: Path, id_offset: int) -> list[dict]:
    import fitz  # PyMuPDF

    print("\n=== PDF ===")
    queries = []
    for i, (filename, query, body) in enumerate(_PDF_TOPICS, start=id_offset):
        path = out_dir / filename
        doc = fitz.open()
        page = doc.new_page()
        rect = fitz.Rect(50, 50, 550, 800)
        page.insert_htmlbox(rect, f"<p>{body.replace(chr(10), '<br>')}</p>")
        doc.save(str(path))
        doc.close()
        queries.append({
            "id": i,
            "file_type": "pdf",
            "query": query,
            "kind": "semantic",
            "relevant": [filename],
        })
        print(f"  {filename}  <- \"{query}\"")
    return queries


