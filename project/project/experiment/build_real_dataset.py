# ---------------------------------------------------------------------------
# Flickr8k
# ---------------------------------------------------------------------------

ROWS_API = (
    "https://datasets-server.huggingface.co/rows"
    "?dataset=jxie%2Fflickr8k&config=default&split=train"
    "&offset={offset}&length={length}"
)


def _fetch_flickr_rows(n: int) -> list[dict]:
    url = ROWS_API.format(offset=0, length=n)
    with urllib.request.urlopen(url, timeout=60) as resp:
        return json.loads(resp.read().decode())["rows"]


def _build_images(out_dir: Path, n: int) -> list[dict]:
    print(f"\n=== Изображения (Flickr8k, {n} фото) ===")
    rows = _fetch_flickr_rows(n)
    queries = []
    for i, row in enumerate(rows, start=1):
        r = row["row"]
        filename = f"flickr_{i:03d}.jpg"
        urllib.request.urlretrieve(r["image"]["src"], out_dir / filename)
        captions = [r[f"caption_{j}"].strip().rstrip(" .") for j in range(5)]
        query = min(captions, key=len).lower()
        queries.append({
            "id": i,
            "file_type": "image",
            "query": query,
            "kind": "semantic",
            "relevant": [filename],
        })
        print(f"  [{i}/{n}] {filename}  <- \"{query}\"")
        time.sleep(0.15)
    return queries


