def _build_docx(out_dir: Path, id_offset: int) -> list[dict]:
    import docx as python_docx

    print("\n=== DOCX ===")
    queries = []
    for i, (filename, query, paragraphs) in enumerate(_DOCX_TOPICS, start=id_offset):
        path = out_dir / filename
        doc = python_docx.Document()
        for para in paragraphs:
            doc.add_paragraph(para)
        doc.save(str(path))
        queries.append({
            "id": i,
            "file_type": "docx",
            "query": query,
            "kind": "semantic",
            "relevant": [filename],
        })
        print(f"  {filename}  <- \"{query}\"")
    return queries


