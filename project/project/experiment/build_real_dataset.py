def main() -> None:
    parser = argparse.ArgumentParser(
        description="Строит смешанный датасет: реальные фото + документы всех типов"
    )
    parser.add_argument("--out", type=Path, default=Path(__file__).parent / "real_dataset")
    parser.add_argument("--images", type=int, default=20, help="Число фото из Flickr8k")
    args = parser.parse_args()

    out_dir: Path = args.out
    if out_dir.exists():
        import shutil
        shutil.rmtree(out_dir)
    out_dir.mkdir(parents=True)

    all_queries: list[dict] = []

    # 1. Изображения
    all_queries += _build_images(out_dir, args.images)

    # 2. Документы
    offset = len(all_queries) + 1
    all_queries += _build_pdfs(out_dir, offset)
    offset = len(all_queries) + 1
    all_queries += _build_docx(out_dir, offset)
    offset = len(all_queries) + 1
    all_queries += _build_txts(out_dir, offset)
    offset = len(all_queries) + 1
    all_queries += _build_csvs(out_dir, offset)
    offset = len(all_queries) + 1
    all_queries += _build_xlsx(out_dir, offset)
    offset = len(all_queries) + 1

    # 3. Точные запросы по именам файлов
    all_queries += _build_exact_queries(offset)

    # Пересчитываем id последовательно
    for idx, q in enumerate(all_queries, start=1):
        q["id"] = idx

    total_files = len(list(out_dir.iterdir()))
    semantic = sum(1 for q in all_queries if q["kind"] == "semantic")
    exact    = sum(1 for q in all_queries if q["kind"] == "exact")

    manifest = {
        "_note": (
            f"Смешанный датасет: {args.images} реальных фото (Flickr8k) + "
            f"документы PDF/DOCX/TXT/CSV/XLSX с содержательным текстом на конкретные темы. "
            f"Итого файлов: {total_files}, запросов: {len(all_queries)} "
            f"({semantic} семантических, {exact} точных)."
        ),
        "queries": all_queries,
    }

    queries_path = out_dir.parent / "real_queries.json"
    queries_path.write_text(
        json.dumps(manifest, ensure_ascii=False, indent=2), encoding="utf-8"
    )

    print(f"\n{'='*60}")
    print(f"Готово!")
    print(f"  Файлов в датасете : {total_files}")
    print(f"  Запросов всего    : {len(all_queries)}")
    print(f"    семантических   : {semantic}")
    print(f"    точных (exact)  : {exact}")
    print(f"  Сохранено в       : {out_dir}")
    print(f"  Запросы           : {queries_path}")
    print(f"{'='*60}")
    print(f"\nДалее:")
    print(f"  1. POST /index {{\"path\": \"{out_dir.resolve()}\"}}")
    print(f"  2. python run_experiment.py --dataset {out_dir} --queries {queries_path}")


if __name__ == "__main__":
    main()
